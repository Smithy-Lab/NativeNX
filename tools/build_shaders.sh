# The window's own shaders (gfx/shaders: FSR's compute shaders, the pop-ups' quad) → SPIR-V words in gfx/shaders/shaders_spv.h, which is kept in the
# repository so that building nxlinux needs no GLSL compiler. Run again after changing a shader:
#   tools/build_shaders.sh [path to glslangValidator]
set -e
G=${1:-glslangValidator}
D=$(cd "$(dirname "$0")/.." && pwd)
T=$(mktemp -d)
for s in fsr_easu fsr_rcas; do "$G" -V --target-env vulkan1.1 -I"$D/third_party/fsr" -o "$T/$s.spv" "$D/gfx/shaders/$s.comp" > /dev/null; done
"$G" -V --target-env vulkan1.1 -o "$T/overlay_vert.spv" "$D/gfx/shaders/overlay.vert" > /dev/null   # the pop-ups (vk_overlay.c)
"$G" -V --target-env vulkan1.1 -o "$T/overlay_frag.spv" "$D/gfx/shaders/overlay.frag" > /dev/null
python3 - "$T" "$D/gfx/shaders/shaders_spv.h" fsr_easu fsr_rcas overlay_vert overlay_frag <<'PY'
import sys, struct
t, out, names = sys.argv[1], sys.argv[2], sys.argv[3:]
L = ['// Generated by tools/build_shaders.sh from gfx/shaders/*.comp (FSR: third_party/fsr): do not edit', '#pragma once', '#include <stdint.h>']
for n in names:
    b = open(f'{t}/{n}.spv', 'rb').read(); w = struct.unpack(f'<{len(b) // 4}I', b)
    L.append(f'static const uint32_t spv_{n}[{len(w)}] = {{')
    for i in range(0, len(w), 12): L.append('    ' + ','.join(f'{x:#010x}' for x in w[i:i + 12]) + ',')
    L.append('};')
open(out, 'w').write('\n'.join(L) + '\n')
PY
rm -rf "$T"
echo "wrote gfx/shaders/shaders_spv.h"
