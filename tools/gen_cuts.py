# nxnative's registered per-build cuts → a C table (nxl_cuts.c) the loader applies to a module of that build before it is
# recompiled. The tables are nxnative's own: dm/tools/sdk_patches.py (Nintendo SDK module builds) and dm/games/*/patches.py
# (games' own modules), each CUTS = {build ID: [(offset, original bytes hex, new bytes hex, reason)]}. The loader checks
# every original byte first, as nxnative's patch_nso.py does, and applies a build's cuts all or none.
# Usage: gen_cuts.py <nxnative dm folder> <output .c>
import sys, os, glob, importlib.util

dm, out = sys.argv[1], sys.argv[2]
sys.path.insert(0, os.path.join(dm, 'tools'))   # the patch files import nso_asm's encoders
files = [os.path.join(dm, 'tools', 'sdk_patches.py')] + sorted(glob.glob(os.path.join(dm, 'games', '*', 'patches.py')))
cuts, where = {}, {}
for n, path in enumerate(files):
    if not os.path.exists(path): continue
    try:
        spec = importlib.util.spec_from_file_location(f'nxl_patches_{n}', path)
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
    except Exception as e:
        print(f'gen_cuts: skipping {path}: {e!r}', file=sys.stderr)
        continue
    for bid, v in getattr(m, 'CUTS', {}).items():
        if bid in cuts: sys.exit(f'gen_cuts: build {bid} in both {where[bid]} and {path}')
        cuts[bid], where[bid] = v, path

def cstr(s): return '"' + s.encode('ascii', 'replace').decode().replace('\\', '\\\\').replace('"', '\\"') + '"'
def hexbytes(h):
    b = bytes.fromhex(h) if isinstance(h, str) else bytes(h)
    return b

lines = ['// Generated by tools/gen_cuts.py from nxnative\'s sdk_patches.py and games/*/patches.py: do not edit', '#include <stdint.h>',
         '#include <stddef.h>', 'typedef struct { const char *build; uint32_t off, len; const uint8_t *orig, *repl; const char *why; } nxl_cut;',
         'const nxl_cut nxl_cuts[] = {']
total = 0
for bid in sorted(cuts):
    for off, ob, nb, why in cuts[bid]:
        o, r = hexbytes(ob), hexbytes(nb)
        assert len(o) == len(r), (bid, off)
        arr = lambda b: '(const uint8_t[]){' + ','.join(str(x) for x in b) + '}'
        lines.append(f'    {{"{bid}", {off:#x}, {len(o)}, {arr(o)}, {arr(r)}, {cstr(str(why))}}},')
        total += 1
lines += ['};', f'const size_t nxl_ncuts = {total};', '']
tmp = out + '.tmp'
with open(tmp, 'w') as f: f.write('\n'.join(lines))
os.replace(tmp, out)
