"""Write nxnative's NVN name table as C.

usage: nvn_names.py <nxnative dm/gfx/nvn/nvn_thunks.S> <output.c>

nxnative generates nvn_thunks.S (dm/gfx/tools/gen_protos.py): ARM64 counting thunks, a table of their addresses and
nvn_names, the NVN entry point names in slot order. nxlinux needs only the names: its entry points are generated thunks
(compat/nxnative/patches/hle_nvn.py), so the table is read out of the assembly ("LnK: .asciz ...", in K order).
"""
import re
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    names = {}
    for line in open(sys.argv[1], encoding="utf-8"):
        m = re.match(r'\s*Ln(\d+):\s*\.asciz\s+"([^"]*)"', line)
        if m:
            names[int(m.group(1))] = m.group(2)
    n = len(names)
    if not n or sorted(names) != list(range(n)):
        sys.exit(f"{sys.argv[1]}: the name table is not a contiguous Ln0..LnN list")
    body = "".join(f'    "{names[i]}",\n' for i in range(n))
    text = (f"// generated by tools/nvn_names.py from nxnative's nvn_thunks.S: do not edit\n"
            f"const char *nvn_names[{n}] = {{\n{body}}};\n"
            "// identities only: hle_nvn.c compares slot entries with them, so their bodies differ (never merged)\n"
            "volatile int nvn_entry_marks[3];\n"
            "void nvn_unimpl_entry(void) { nvn_entry_marks[0] = 1; }\n"
            "void nvn_prof_entry(void) { nvn_entry_marks[1] = 2; }\n"
            "void nvn_big_entry(void) { nvn_entry_marks[2] = 3; }\n")
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
